export const ALL_ALERTS: readonly AlertRule[] = [
  ...SLOS.flatMap((slo) => tiersOf(slo).map((tier) => burnAlert(slo, tier))),
  ...EXTRA_ALERTS,
];

const q = (text: string): string => JSON.stringify(text);

/**
 * The Prometheus rule file. A bad-event series that has never existed (no 5xx yet) would leave the
 * ratio empty, and an empty ratio never alerts, so `or vector(0)` turns "none yet" into zero.
 *
 * The file, written to `ops/prometheus/rules.yaml`. Do not edit it by hand. */
export function renderRules(): string {
  const lines: string[] = [
    '# Generated by `npm run ops:generate` from packages/observability/src/slo. Do not edit by hand.',
    '# SLO targets and alert tiers live in slos.ts; metric names come from the catalog.',
    'groups:',
    '  - name: slo-error-ratios',
    '    interval: 30s',
    '    rules:',
  ];
  for (const slo of SLOS) {
    for (const w of WINDOWS) {
      lines.push(
        `      - record: ${recordName(w)}`,
        `        expr: ${q(`(${slo.bad(w)} or vector(0)) / ${slo.total(w)}`)}`,
        '        labels:',
        `          slo: ${q(slo.id)}`,
        `          service: ${q(slo.service)}`,
        `          objective: ${q(String(slo.objective))}`,
      );
    }
  }
  lines.push('  - name: slo-alerts', '    rules:');
  for (const rule of ALL_ALERTS) {
    lines.push(
      `      - alert: ${rule.alert}`,
      `        expr: ${q(rule.expr)}`,
      `        for: ${rule.for}`,
      '        labels:',
      `          severity: ${rule.severity}`,
      ...(rule.slo ? [`          slo: ${q(rule.slo)}`] : []),
      '        annotations:',
      `          summary: ${q(rule.summary)}`,
      `          description: ${q(rule.description)}`,
      `          runbook: ${q(rule.runbook)}`,
    );
  }
  return `${lines.join('\n')}\n`;
}

