export interface AlertRule {
  alert: string;
  expr: string;
  for: string;
  severity: 'page' | 'ticket';
  summary: string;
  description: string;
  /** Path in this repository, so the page links to what to do about it. */
  runbook: string;
  slo?: string;
}

const pascal = (text: string): string =>
  text
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('');

export const recordName = (w: string): string => `slo:sli_error:ratio_rate${w}`;

export function burnAlert(slo: Slo, tier: Tier): AlertRule {
  const t = threshold(slo, tier);
  const at = (w: string) => `${recordName(w)}{slo="${slo.id}"} > ${t}`;
  const spend = ((tier.burn * parseHours(tier.long)) / (30 * 24)) * 100;
  return {
    alert: `${pascal(slo.id)}${pascal(tier.name)}Burn`,
    expr: `${at(tier.long)} and ${at(tier.short)}`,
    for: tier.for,
    severity: tier.severity,
    summary: `${slo.title}: the error budget is burning ${tier.burn}x too fast`,
    description:
      `More than ${(t * 100).toFixed(2)}% of events are bad over both ${tier.long} and ${tier.short}. ` +
      `At this rate ${spend.toFixed(1)}% of the 30-day budget goes in ${tier.long}. ${slo.meaning}`,
    runbook: `docs/runbooks/${slo.id}.md`,
    slo: slo.id,
  };
}

const parseHours = (w: string): number => {
  const n = Number(w.slice(0, -1));
  return w.endsWith('d') ? n * 24 : w.endsWith('h') ? n : n / 60;
};

